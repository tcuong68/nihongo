/* Loại bỏ mục trùng lặp và ký tự không phải kanji, chỉ giữ lần xuất hiện đầu tiên.
   `exclude` để bảng N4 không lặp lại những chữ đã có trong bảng N5. */
function dedupeKanji(list, exclude) {
  const seen = new Set(exclude || []);
  return list.filter(k => {
    const ok = /^[一-鿿]$/.test(k.c) && !seen.has(k.c);
    if (ok) seen.add(k.c);
    return ok;
  });
}

